#!/usr/bin/env node
// Runs before `next build` (see package.json "build").
//
// Why: SiteGround's Node.js build runs a `fix_typescript` step after `npm install` that deletes our
// next.config.mjs / postcss.config.mjs and injects its own next config, which drops our .tsx app
// routes (the site then only has /404). This script puts our config back, without losing the
// host's: it renames the host's next config to next.config.host.* and writes our next.config.mjs,
// which loads the host config, spreads it, and applies ours on top.
//
// It only ever touches next.config.* and postcss.config.* in the project root. Never src/, .env*,
// or anything else. When the configs are already ours (local dev, the repo), it only logs.

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const MARKER = "// signal-desk:own-config";
const P = "[sg-prepare]";

// Our next.config.mjs. The committed next.config.mjs is byte-for-byte this string (a test checks it).
const NEXT_CONFIG = `${MARKER}
// Generated by scripts/sg-prepare-build.cjs; the committed copy is identical. Edit the script, then run:
//   node scripts/sg-prepare-build.cjs --print-next-config > next.config.mjs
//
// If a host (e.g. SiteGround) injected its own next config, it was renamed to next.config.host.*.
// We load it, spread it, and apply our settings on top, so the host's settings are kept.

import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const HOST_FILES = ["next.config.host.mjs", "next.config.host.cjs", "next.config.host.js", "next.config.host.mts", "next.config.host.ts"];

const isDev = process.env.NODE_ENV !== "production";

// Next.js injects inline bootstrap scripts, so 'unsafe-inline' is needed without a nonce setup.
// Everything is same-origin: the browser never talks to Microsoft Graph directly.
const csp = [
  "default-src 'self'",
  \`script-src 'self' 'unsafe-inline'\${isDev ? " 'unsafe-eval'" : ""}\`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  \`connect-src 'self'\${isDev ? " ws:" : ""}\`,
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const OUR_HEADERS = [
  {
    source: "/:path*",
    headers: [
      { key: "Content-Security-Policy", value: csp },
      { key: "X-Content-Type-Options", value: "nosniff" },
      { key: "X-Frame-Options", value: "DENY" },
      { key: "Referrer-Policy", value: "no-referrer" },
      { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
      { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
      { key: "X-Robots-Tag", value: "noindex, nofollow" },
    ],
  },
];

async function loadHostConfig(phase, ctx) {
  for (const file of HOST_FILES) {
    const full = path.join(here, file);
    if (!existsSync(full)) continue;
    try {
      const mod = await import(pathToFileURL(full).href);
      let cfg = mod.default ?? mod;
      if (typeof cfg === "function") cfg = await cfg(phase, ctx);
      console.log(\`[signal-desk] merged host config from \${file}\`);
      return cfg && typeof cfg === "object" ? cfg : {};
    } catch (e) {
      console.warn(\`[signal-desk] could not load \${file} (\${e && e.message}); using our config only\`);
      return {};
    }
  }
  return {};
}

/** @type {(phase: string, ctx: unknown) => Promise<import("next").NextConfig>} */
export default async function signalDeskConfig(phase, ctx) {
  const host = await loadHostConfig(phase, ctx);
  const hostHeaders = typeof host.headers === "function" ? host.headers : null;
  const merged = {
    ...host,
    pageExtensions: ["tsx", "ts", "jsx", "js"],
    poweredByHeader: false,
    async headers() {
      const theirs = hostHeaders ? (await hostHeaders()) ?? [] : [];
      return [...theirs, ...OUR_HEADERS];
    },
  };
  // The app needs a Node server (API routes, login); a static export would break it.
  if (merged.output === "export") {
    console.warn('[signal-desk] ignoring host output: "export" (the app needs a server)');
    delete merged.output;
  }
  return merged;
}
`;

const POSTCSS_CONFIG = `export default {
  plugins: { "@tailwindcss/postcss": {} },
};
`;

// The order Next.js looks for its config in; the first one found wins.
const NEXT_CONFIG_NAMES = ["next.config.js", "next.config.mjs", "next.config.ts", "next.config.mts", "next.config.cjs", "next.config.cts"];

function isEsm(file, contents, root) {
  const ext = path.extname(file);
  if (ext === ".mjs" || ext === ".mts") return true;
  if (ext === ".cjs" || ext === ".cts") return false;
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
    if (pkg.type === "module") return true;
  } catch {
    /* no package.json type: fall back to the contents */
  }
  return /^\s*(export\s|import\s)/m.test(contents);
}

/** Name to rename a foreign next config to, keeping its module type (and TypeScript if it was TS). */
function hostName(file, contents, root) {
  const ext = path.extname(file);
  const esm = isEsm(file, contents, root);
  if (ext === ".ts" || ext === ".mts" || ext === ".cts") return esm ? "next.config.host.mts" : "next.config.host.ts";
  return esm ? "next.config.host.mjs" : "next.config.host.cjs";
}

function prepare(root, log = console.log) {
  const entries = fs.readdirSync(root);
  const configs = entries
    .filter((f) => /^(next|postcss)\.config\.[^.]+$/.test(f) && fs.statSync(path.join(root, f)).isFile())
    .sort();

  // (a) Show exactly what the host left us, so it appears in the build log.
  if (!configs.length) log(`${P} no next.config.* or postcss.config.* found in ${root}`);
  for (const f of configs) {
    const text = fs.readFileSync(path.join(root, f), "utf8");
    log(`${P} ----- ${f} (${Buffer.byteLength(text)} bytes) -----`);
    for (const line of text.split(/\r?\n/)) log(`${P} | ${line}`);
    log(`${P} ----- end of ${f} -----`);
  }

  const actions = [];

  // (b) Rename any next config that isn't ours, in Next's lookup order (first one = the one Next used).
  const foreign = NEXT_CONFIG_NAMES.filter((f) => entries.includes(f)).filter(
    (f) => !fs.readFileSync(path.join(root, f), "utf8").startsWith(MARKER),
  );
  foreign.forEach((f, i) => {
    const contents = fs.readFileSync(path.join(root, f), "utf8");
    let target = hostName(f, contents, root);
    if (i > 0) target = target.replace("next.config.host.", `next.config.host-unused-${i}.`);
    if (fs.existsSync(path.join(root, target))) fs.rmSync(path.join(root, target));
    fs.renameSync(path.join(root, f), path.join(root, target));
    actions.push(`renamed host config ${f} -> ${target}`);
  });

  // (c) Write our next.config.mjs unless ours is already there.
  const ours = path.join(root, "next.config.mjs");
  if (fs.existsSync(ours) && fs.readFileSync(ours, "utf8").startsWith(MARKER)) {
    log(`${P} next.config.mjs is already ours: leaving it`);
  } else {
    fs.writeFileSync(ours, NEXT_CONFIG);
    actions.push("wrote our next.config.mjs (loads next.config.host.* if present, ours applied on top)");
  }

  // (d) Write postcss.config.mjs only if there is no postcss config at all.
  const postcss = fs.readdirSync(root).filter((f) => /^postcss\.config\.[^.]+$/.test(f));
  if (!postcss.length) {
    fs.writeFileSync(path.join(root, "postcss.config.mjs"), POSTCSS_CONFIG);
    actions.push("wrote postcss.config.mjs (Tailwind)");
  } else {
    log(`${P} postcss config present (${postcss.join(", ")}): leaving it`);
    for (const f of postcss) {
      if (!fs.readFileSync(path.join(root, f), "utf8").includes("@tailwindcss/postcss")) {
        log(`${P} WARNING: ${f} does not load @tailwindcss/postcss, so styles may be missing`);
      }
    }
  }

  if (actions.length) actions.forEach((a) => log(`${P} ${a}`));
  else log(`${P} nothing to change: configs are already ours`);
  return actions;
}

module.exports = { MARKER, NEXT_CONFIG, POSTCSS_CONFIG, prepare, hostName };

if (require.main === module) {
  if (process.argv.includes("--print-next-config")) {
    process.stdout.write(NEXT_CONFIG);
  } else {
    prepare(path.resolve(__dirname, ".."));
  }
}
